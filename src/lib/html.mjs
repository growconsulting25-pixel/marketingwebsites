// Tiny templating helpers. Content is authored in this repo, so interpolated
// values are trusted HTML unless passed through esc().

export const esc = (s) =>
  String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

const flat = (v) => (Array.isArray(v) ? v.map(flat).join('') : v == null || v === false ? '' : String(v));

export const html = (strings, ...vals) =>
  strings.reduce((out, s, i) => out + s + (i < vals.length ? flat(vals[i]) : ''), '');

// Placeholders for content that must be verified before launch (proof,
// testimonials, case studies…). Collected so the build can report them.
export const todos = [];
let currentPage = '';
export const setCurrentPage = (p) => { currentPage = p; };
export const todo = (label, { block = false } = {}) => {
  todos.push({ page: currentPage, label });
  const tag = block ? 'div' : 'span';
  return `<${tag} class="todo" data-todo>${esc(label)}</${tag}>`;
};

// Hero H1 word animation: wraps each word in a span with an index.
export const animWords = (text) => {
  let i = 0;
  return text
    .split(/(<em>.*?<\/em>)|\s+/)
    .filter(Boolean)
    .map((w) => `<span class="w" style="--i:${i++}">${w}</span>`)
    .join(' ');
};

